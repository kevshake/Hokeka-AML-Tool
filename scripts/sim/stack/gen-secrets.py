"""Generate (once) the local-only secrets the sim Control Plane needs, as a dotenv file.

Usage: py scripts/sim/stack/gen-secrets.py [out_file]
Default out file: scripts/sim/results/sim-secrets.env (gitignored via results/).
Existing values are kept so restarts keep the same keys (edge pins, encrypted columns).
"""
import base64
import os
import secrets
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "results", "sim-secrets.env")


def load(path):
    vals = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, v = line.split("=", 1)
                    vals[k] = v
    return vals


def openssl_keypair(alg):
    """Return (base64 PKCS#8 DER private, base64 SPKI DER public) using the openssl CLI."""
    priv_der = subprocess.run(["openssl", "genpkey", "-algorithm", alg, "-outform", "DER"],
                              check=True, capture_output=True).stdout
    pub_der = subprocess.run(["openssl", "pkey", "-inform", "DER", "-pubout", "-outform", "DER"],
                             input=priv_der, check=True, capture_output=True).stdout
    return base64.b64encode(priv_der).decode(), base64.b64encode(pub_der).decode()


def main():
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    vals = load(out)
    enc = base64.b64encode(secrets.token_bytes(32)).decode()
    wanted = {
        "JWT_SECRET": secrets.token_urlsafe(64),
        "ENCRYPTION_KEY": enc,
        "SECURITY_ENCRYPTION_KEY": vals.get("ENCRYPTION_KEY", enc),
        "AUDIT_HMAC_KEY": secrets.token_urlsafe(48),
        "PII_LOOKUP_HMAC_KEY": secrets.token_urlsafe(48),
        "AML_MS_INTERNAL_KEY": "sim-internal-key-" + secrets.token_hex(16),
        "AUTH_PASSWORD_RESET_PEPPER": secrets.token_urlsafe(48),
        "SEED_ADMIN_PASSWORD":"SimAdmin!" + secrets.token_hex(8),
    }
    # Long-term edge-channel keys (HSE-1). Without them the Control Plane generates EPHEMERAL keys
    # at every start and an enrolled edge rejects bundles after a CP restart.
    if "EDGE_BUNDLE_SIGNING_KEY" not in vals:
        priv, pub = openssl_keypair("ed25519")
        wanted["EDGE_BUNDLE_SIGNING_KEY"], wanted["EDGE_BUNDLE_SIGNING_PUBLIC_KEY"] = priv, pub
    if "EDGE_METRICS_INGEST_KEY" not in vals:
        priv, pub = openssl_keypair("x25519")
        wanted["EDGE_METRICS_INGEST_KEY"], wanted["EDGE_METRICS_INGEST_PUBLIC_KEY"] = priv, pub
    changed = False
    for k, v in wanted.items():
        if k not in vals:
            vals[k] = v
            changed = True
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# hokeka-sim local secrets — generated by gen-secrets.py. Never use outside the sim.\n")
        for k, v in vals.items():
            fh.write(f"{k}={v}\n")
    print(("updated " if changed else "unchanged ") + out)


if __name__ == "__main__":
    main()
